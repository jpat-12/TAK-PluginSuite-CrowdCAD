"""Generate cloudtak/plugin/lib/incident-icon-data.ts from the ATAK plugin's incident icon.

    python cloudtak/make_incident_icon.py

One icon for both clients: atak/app/src/main/res/drawable-nodpi/cc_incident_ems.png (the EMS
Star of Life from iconset/svgs/…genric-ems-plain) is downscaled to 64 px and embedded as a data URL, so
the CloudTAK panel needs no asset pipeline (plugins compile inside CloudTAK's own build). The
panel tints it by priority exactly as ATAK's IncidentStyler does (lib/incident-icon.ts).
Re-run after changing the ATAK drawable; don't hand-edit the .ts.
"""
import base64
import io
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "atak" / "app" / "src" / "main" / "res" / "drawable-nodpi" / "cc_incident_ems.png"
OUT = ROOT / "cloudtak" / "plugin" / "lib" / "incident-icon-data.ts"
SIZE = 64

image = Image.open(SOURCE).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
png = io.BytesIO()
image.save(png, format="PNG", optimize=True)
data = base64.b64encode(png.getvalue()).decode()
OUT.write_text(
    "// GENERATED by cloudtak/make_incident_icon.py from the ATAK plugin's cc_incident_ems.png. Don't edit.\n"
    f"export const INCIDENT_ICON_SIZE = {SIZE};\n"
    f"export const INCIDENT_ICON_PNG = 'data:image/png;base64,{data}';\n",
    encoding="utf-8")
print(f"wrote {OUT} ({len(data)} base64 chars)")
