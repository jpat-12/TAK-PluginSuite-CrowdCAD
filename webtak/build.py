#!/usr/bin/env python3
"""Bundle plugin/ into ONE classic-script IIFE that WebTAK's loadScript() can load (it injects
a plain <script>, so import/export are illegal) — the same dependency-ordered concatenation
WebTAK-Plugin-Channels' build.js does, in Python so the infra-TAK installer can build it on a
host without node, and no generated bundle is ever committed.

    python3 webtak/build.py [--url URL] [--token TOKEN] [--out FILE]

--url / --token bake the bridge's public URL and board token into the bundle (install.sh
passes them); without them the panel asks for both in its Settings.
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "plugin", "src")
DEFAULT_OUT = os.path.join(HERE, "dist", "crowdcad-board.plugin.js")

# Dependency order: config first, core (constructs the singleton) last, then the entry.
MODULES = ["config.js", "board-client.js", "format.js", "styles.js", "dispatch-window.js", "ui.js",
           "floating-panel.js", "core.js"]

IMPORT = re.compile(r"^\s*import\s.+\sfrom\s.+;?\s*$")


def strip_module_syntax(code):
    out = []
    for line in code.split("\n"):
        if IMPORT.match(line):
            continue
        line = re.sub(r"^\s*export\s+default\s+.+;?\s*$", "", line)
        line = re.sub(r"^\s*export\s*\{[^}]*\};?\s*$", "", line)
        line = re.sub(r"^(\s*)export\s+", r"\1", line)
        out.append(line)
    return "\n".join(out)


def js_string(value):
    """Safe inside a single-quoted JS literal (the placeholders sit in '…')."""
    return value.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "").replace("<", "\\x3c")


def build(url="", token="", version=""):
    parts = ["/* CrowdCAD for TAK — WebTAK board plugin (classic script). Generated by build.py; do not edit. */",
             "(function () {", "'use strict';"]
    for name in MODULES:
        with open(os.path.join(SRC, name), encoding="utf-8") as stream:
            parts.append(f"\n/* ===== src/{name} ===== */\n" + strip_module_syntax(stream.read()))
    parts.append("\n/* ===== WebTAK entry (plugin/index.js) ===== */\nconst board = instance;")
    with open(os.path.join(HERE, "plugin", "index.js"), encoding="utf-8") as stream:
        parts.append(strip_module_syntax(stream.read()))
    parts.append("})();\n")
    out = "\n".join(parts)
    for placeholder, value in (("__CROWDCAD_TAK_URL__", url.rstrip("/")), ("__CROWDCAD_TAK_TOKEN__", token),
                               ("__CROWDCAD_TAK_VERSION__", version)):
        if value:
            out = out.replace(placeholder, js_string(value))
    leaked = [l for l in out.split("\n") if re.match(r"^\s*(import|export)\s", l)]
    if leaked:
        raise SystemExit("ERROR: ESM syntax leaked into bundle:\n" + "\n".join(leaked))
    return out


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--url", default=os.environ.get("CROWDCAD_TAK_URL", ""))
    parser.add_argument("--token", default=os.environ.get("CROWDCAD_TAK_TOKEN", ""))
    parser.add_argument("--out", default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    try:
        with open(os.path.join(HERE, "..", "VERSION"), encoding="utf-8") as stream:
            version = stream.read().strip()
    except OSError:
        version = ""
    bundle = build(args.url, args.token, version)
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    old = os.umask(0o022)
    with open(args.out, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(bundle)
    os.umask(old)
    print(f"Built {args.out} ({len(bundle) / 1024:.1f} KB{', bridge baked in' if args.url else ''})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
